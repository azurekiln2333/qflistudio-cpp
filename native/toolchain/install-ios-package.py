#!/usr/bin/env python3
"""Enable a downloaded native iOS package in this Flutter checkout."""

import argparse
import hashlib
import json
from pathlib import Path


def main():
    repo = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--package', type=Path, default=repo / 'native/build/ios-portable/package')
    args = parser.parse_args()
    package = args.package.resolve()
    if any(character in str(package) for character in '\n\r"$#'):
        raise ValueError('Package path contains unsupported xcconfig characters')
    report_path = package / 'manifests/assembly.json'
    if not report_path.is_file():
        report_path = package / 'manifests/slice.json'
    report = json.loads(report_path.read_text())
    if report.get('platform') != 'ios' or report.get('nativeLinkVerified') is not True:
        raise ValueError('Expected a validated iOS native package')
    for relative, expected in report['libraries'].items():
        library = (package / relative).resolve()
        if not library.is_relative_to(package):
            raise ValueError(f'Unsafe package path: {relative}')
        with library.open('rb') as stream:
            if hashlib.file_digest(stream, 'sha256').hexdigest() != expected:
                raise ValueError(f'Library checksum mismatch: {relative}')
    for relative in ('resources/sdk/toolchain.json',
                     'resources/sdk/share/wasi-sysroot/lib/wasm32-wasip1/eh/libunwind.a',
                     'include/qfli_compiler.h', 'include/qfli_wasm.h'):
        if not (package / relative).is_file():
            raise ValueError(f'Missing iOS package file: {relative}')
    for directory, field in (('resources', 'resourcesSha256'), ('include', 'headersSha256')):
        inventory = {}
        for path in sorted((package / directory).rglob('*')):
            if path.is_symlink():
                raise ValueError(f'Unexpected symbolic link: {path}')
            if path.is_file():
                with path.open('rb') as stream:
                    inventory[path.relative_to(package / directory).as_posix()] = hashlib.file_digest(stream, 'sha256').hexdigest()
        digest = hashlib.sha256(json.dumps(inventory, sort_keys=True).encode()).hexdigest()
        if digest != report[field]:
            raise ValueError(f'iOS package {directory} checksum mismatch')
    config = repo / 'ios/Flutter/NativeRuntime.generated.xcconfig'
    config.write_text(
        '// Generated by native/toolchain/install-ios-package.py.\n'
        f'QFLI_RUNTIME_PACKAGE = {package.as_posix()}\n'
        'QFLI_PORTABLE_ENABLED = 1\n'
        'GCC_PREPROCESSOR_DEFINITIONS = $(inherited) QFLI_PORTABLE_RUNTIME=1\n'
        'LIBRARY_SEARCH_PATHS = $(inherited) "$(QFLI_RUNTIME_PACKAGE)/$(PLATFORM_NAME)"\n'
        'OTHER_LDFLAGS = $(inherited) -lqfli_portable -lc++ -framework Foundation\n',
        encoding='utf-8')
    print(f'Enabled native package: {package}\nXcode configuration: {config}')


if __name__ == '__main__':
    main()
